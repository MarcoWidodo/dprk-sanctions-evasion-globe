// Computes network metrics for every actor and writes data/metrics.js.
// Run from the repo root: node scripts/build-metrics.js
//
// Broker score = betweenness centrality (Brandes, unweighted, undirected) over the
// actor-to-actor links in DATA.adj. It measures how often an actor sits on the
// shortest path between two others. This is our own measure, not RAND's weighted
// subgroup betweenness.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const ctx = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'data/data.js'), 'utf8') + ';this.DATA=DATA;', ctx);
const { entities, adj } = ctx.DATA;
const n = entities.length;

const nbrs = Array.from({ length: n }, () => []);
const degree = new Array(n).fill(0);
for (const [k, items] of Object.entries(adj)) {
  const i = +k;
  degree[i] = items.length;
  for (const [ref] of items) if (typeof ref === 'number' && ref !== i) nbrs[i].push(ref);
}

const btw = new Float64Array(n);
for (let s = 0; s < n; s++) {
  const stack = [], preds = Array.from({ length: n }, () => []);
  const sigma = new Float64Array(n), dist = new Int32Array(n).fill(-1);
  sigma[s] = 1; dist[s] = 0;
  const queue = [s];
  for (let h = 0; h < queue.length; h++) {
    const v = queue[h]; stack.push(v);
    for (const w of nbrs[v]) {
      if (dist[w] < 0) { dist[w] = dist[v] + 1; queue.push(w); }
      if (dist[w] === dist[v] + 1) { sigma[w] += sigma[v]; preds[w].push(v); }
    }
  }
  const delta = new Float64Array(n);
  while (stack.length) {
    const w = stack.pop();
    for (const v of preds[w]) delta[v] += (sigma[v] / sigma[w]) * (1 + delta[w]);
    if (w !== s) btw[w] += delta[w];
  }
}
// undirected graph: every pair was counted from both ends
for (let i = 0; i < n; i++) btw[i] /= 2;

// rank 1 = strongest broker; actors that broker nothing get no rank (0)
const order = [...Array(n).keys()].filter(i => btw[i] > 0).sort((a, b) => btw[b] - btw[a]);
const rank = new Array(n).fill(0);
order.forEach((i, r) => { rank[i] = r + 1; });

// largest connected component, for the story
const comp = new Int32Array(n).fill(-1);
let biggest = 0;
for (let s = 0, c = 0; s < n; s++) {
  if (comp[s] >= 0) continue;
  let size = 0; const st = [s]; comp[s] = c;
  while (st.length) { const v = st.pop(); size++; for (const w of nbrs[v]) if (comp[w] < 0) { comp[w] = c; st.push(w); } }
  biggest = Math.max(biggest, size); c++;
}

const out = {
  note: 'Generated by scripts/build-metrics.js. Do not edit by hand.',
  degree,
  brokerRank: rank,
  brokerScore: Array.from(btw, v => Math.round(v)),
  ranked: order.length,
  largestComponent: biggest,
};
fs.writeFileSync(path.join(root, 'data/metrics.js'), 'const METRICS = ' + JSON.stringify(out) + ';\n');
console.log(`ranked ${order.length} brokers; largest connected group ${biggest} of ${n}`);
